CREATE DATABASE IF NOT EXISTS QLCuaHang
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QLCuaHang;

CREATE TABLE IF NOT EXISTS NHANVIEN (
  MaNV INT AUTO_INCREMENT PRIMARY KEY,
  HoTen VARCHAR(100) NOT NULL,
  GioiTinh VARCHAR(10) NULL,
  SDT VARCHAR(15) NULL UNIQUE,
  Email VARCHAR(100) NULL UNIQUE,
  TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
  MatKhau VARCHAR(255) NOT NULL,
  VaiTro VARCHAR(30) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS KHACHHANG (
  MaKH INT AUTO_INCREMENT PRIMARY KEY,
  HoTen VARCHAR(100) NOT NULL,
  SDT VARCHAR(15) NULL UNIQUE,
  Email VARCHAR(100) NULL,
  DiemTichLuy INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DANHMUC (
  MaDM INT AUTO_INCREMENT PRIMARY KEY,
  TenDM VARCHAR(100) NOT NULL UNIQUE,
  MoTa VARCHAR(255) NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DODUONG (
  MaDoUong INT AUTO_INCREMENT PRIMARY KEY,
  MaDM INT NOT NULL,
  TenDoUong VARCHAR(150) NOT NULL,
  MoTa VARCHAR(500) NULL,
  DonGia DECIMAL(12,2) NOT NULL CHECK (DonGia >= 0),
  DonViTinh VARCHAR(30) NOT NULL,
  HinhAnh VARCHAR(255) NULL,
  TrangThai VARCHAR(30) NOT NULL DEFAULT 'Đang bán',
  CONSTRAINT fk_dodung_danhmuc FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DONHANG (
  MaDon INT AUTO_INCREMENT PRIMARY KEY,
  MaNV INT NOT NULL,
  MaKH INT NULL,
  NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TongTien DECIMAL(12,2) NOT NULL DEFAULT 0,
  TrangThai VARCHAR(30) NOT NULL,
  GhiChu VARCHAR(500) NULL,
  CONSTRAINT fk_donhang_nhanvien FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV),
  CONSTRAINT fk_donhang_khachhang FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CHITIETDONHANG (
  MaDon INT NOT NULL,
  MaDoUong INT NOT NULL,
  SoLuong INT NOT NULL CHECK (SoLuong > 0),
  DonGiaBan DECIMAL(12,2) NOT NULL CHECK (DonGiaBan >= 0),
  ThanhTien DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (MaDon, MaDoUong),
  CONSTRAINT fk_ctdh_donhang FOREIGN KEY (MaDon) REFERENCES DONHANG(MaDon),
  CONSTRAINT fk_ctdh_dodung FOREIGN KEY (MaDoUong) REFERENCES DODUONG(MaDoUong)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS THANHTOAN (
  MaTT INT AUTO_INCREMENT PRIMARY KEY,
  MaDon INT NOT NULL,
  PhuongThuc VARCHAR(30) NOT NULL,
  SoTien DECIMAL(12,2) NOT NULL CHECK (SoTien >= 0),
  ThoiGianTT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TrangThai VARCHAR(30) NOT NULL,
  CONSTRAINT fk_thanhtoan_donhang FOREIGN KEY (MaDon) REFERENCES DONHANG(MaDon)
) ENGINE=InnoDB;

